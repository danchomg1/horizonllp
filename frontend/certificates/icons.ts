/**
 * Иконки нижнего ряда бланка: часы, календарь и точка на карте.
 *
 * Раньше они были напечатаны в самом бланке. Теперь бланк оставляет там
 * пустоту — ряд собирается целиком на лету, потому что столбец с датами
 * может вообще не появиться. Поэтому контуры перенесены сюда из исходных
 * SVG (sert_sample/*.svg) один в один: viewBox у них в пунктах PDF, так
 * что масштабировать ничего не нужно.
 *
 * Круги, эллипсы и прямоугольник записаны дугами и линиями — pdf-lib
 * понимает только атрибут d, отдельных примитивов у него нет.
 */

export type IconKey = 'duration' | 'calendar' | 'pin';

export interface IconPath {
  d: string;
  /** В исходных SVG у каждого контура либо заливка, либо обводка. */
  mode: 'fill' | 'stroke';
  /** Скруглённые концы линии — как в SVG у стрелки часов. */
  round?: boolean;
}

export interface Icon {
  /** Размеры viewBox; высота у всех трёх одна, ширина отличается. */
  width: number;
  height: number;
  paths: IconPath[];
}

/** Окружность дугами: pdf-lib разбирает их сам. */
function circle(cx: number, cy: number, r: number): string {
  return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
}

function ellipse(cx: number, cy: number, rx: number, ry: number): string {
  return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
}

function rect(x: number, y: number, w: number, h: number): string {
  return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
}

